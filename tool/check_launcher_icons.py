#!/usr/bin/env python3
"""Fails the build when a Flutter template icon would be shipped.

The platform folders are generated by `flutter create`, which fills them with
the Flutter logo. `flutter_launcher_icons` then has to replace every one of
those files. This script proves that it did:

    python tool/check_launcher_icons.py snapshot android ios   # after flutter create
    dart run flutter_launcher_icons                            # replace the icons
    python tool/check_launcher_icons.py verify android ios     # before the build

`snapshot` remembers the hash of every template icon. `verify` fails when an
icon file still has its template hash, when a template icon is gone without a
replacement, or when Android has no adaptive icon.
"""
import hashlib
import json
import sys
from pathlib import Path

SNAPSHOT = Path(".dart_tool/launcher_icon_snapshot.json")

ICON_GLOBS = {
    "android": ["android/app/src/main/res/mipmap-*/*.png"],
    "ios": ["ios/Runner/Assets.xcassets/AppIcon.appiconset/*.png"],
    "web": ["web/favicon.png", "web/icons/*.png"],
    "windows": ["windows/runner/resources/app_icon.ico"],
}

# Files that only exist once our own icons were generated.
REQUIRED_AFTER = {
    "android": ["android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml"],
}


def icon_files(platform):
    files = []
    for pattern in ICON_GLOBS[platform]:
        files.extend(sorted(Path(".").glob(pattern)))
    return files


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def snapshot(platforms):
    data = json.loads(SNAPSHOT.read_text()) if SNAPSHOT.exists() else {}
    for platform in platforms:
        files = icon_files(platform)
        if not files:
            sys.exit(f"error: no {platform} icons found - run `flutter create` first")
        data[platform] = {path.as_posix(): digest(path) for path in files}
        print(f"{platform}: remembered {len(files)} template icons")
    SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
    SNAPSHOT.write_text(json.dumps(data, indent=2) + "\n")


def verify(platforms):
    if not SNAPSHOT.exists():
        sys.exit("error: no snapshot - run the `snapshot` command after `flutter create`")
    data = json.loads(SNAPSHOT.read_text())
    problems = []
    for platform in platforms:
        template = data.get(platform)
        if not template:
            sys.exit(f"error: no snapshot for {platform}")
        for name, template_hash in template.items():
            path = Path(name)
            if not path.exists():
                problems.append(f"{name}: missing")
            elif digest(path) == template_hash:
                problems.append(f"{name}: still the Flutter template icon")
        for name in REQUIRED_AFTER.get(platform, []):
            if not Path(name).exists():
                problems.append(f"{name}: missing")
        if not problems:
            print(f"{platform}: all {len(template)} icons replaced")
    if problems:
        for problem in problems:
            print(f"::error::{problem}")
        sys.exit(
            "error: the app would ship with Flutter template icons. "
            "Check the flutter_launcher_icons configuration."
        )


def main():
    args = sys.argv[1:]
    if len(args) < 2 or args[0] not in ("snapshot", "verify"):
        sys.exit(__doc__)
    unknown = [p for p in args[1:] if p not in ICON_GLOBS]
    if unknown:
        sys.exit(f"error: unknown platform(s): {', '.join(unknown)}")
    (snapshot if args[0] == "snapshot" else verify)(args[1:])


if __name__ == "__main__":
    main()
